#ifndef BOXRIG_UI_SHORTCUT_H
#define BOXRIG_UI_SHORTCUT_H

#include "boxrig/terminal.h"

/** Portable terminal-view command selected by a conventional shortcut. */
typedef enum boxrig_ui_zoom_shortcut {
    /** The event does not select a zoom command. */
    BOXRIG_UI_ZOOM_SHORTCUT_NONE = 0,
    /** Increase the visual font size by one policy step. */
    BOXRIG_UI_ZOOM_SHORTCUT_IN,
    /** Decrease the visual font size by one policy step. */
    BOXRIG_UI_ZOOM_SHORTCUT_OUT,
    /** Restore the visual font size at the start of the zoom sequence. */
    BOXRIG_UI_ZOOM_SHORTCUT_RESET
} boxrig_ui_zoom_shortcut;

/** Portable background-opacity command selected by a sample shortcut. */
typedef enum boxrig_ui_background_opacity_shortcut {
    /** The event does not select a background-opacity command. */
    BOXRIG_UI_BACKGROUND_OPACITY_SHORTCUT_NONE = 0,
    /** Decrease background opacity by ten percentage points. */
    BOXRIG_UI_BACKGROUND_OPACITY_SHORTCUT_DECREASE,
    /** Increase background opacity by ten percentage points. */
    BOXRIG_UI_BACKGROUND_OPACITY_SHORTCUT_INCREASE,
    /** Toggle between 100 percent and the remembered translucent value. */
    BOXRIG_UI_BACKGROUND_OPACITY_SHORTCUT_TOGGLE
} boxrig_ui_background_opacity_shortcut;

/** Portable clipboard command selected by a conventional host shortcut. */
typedef enum boxrig_ui_clipboard_shortcut {
    /** The event does not select a clipboard command. */
    BOXRIG_UI_CLIPBOARD_SHORTCUT_NONE = 0,
    /** Copy the current selection to the host clipboard. */
    BOXRIG_UI_CLIPBOARD_SHORTCUT_COPY,
    /** Paste from the host clipboard. */
    BOXRIG_UI_CLIPBOARD_SHORTCUT_PASTE
} boxrig_ui_clipboard_shortcut;

/**
 * Resolves a portable logical key event to a conventional zoom command.
 *
 * @param event Logical key identity and modifier state to inspect.
 * @return The matching command, or BOXRIG_UI_ZOOM_SHORTCUT_NONE.
 *
 * @remarks Only the initial press selects a command; repeat and release events
 * are ignored. Lock modifiers do not affect matching. Text generated by an
 * input method is deliberately ignored so the same binding can be resolved
 * before terminal input encoding on every frontend.
 */
boxrig_ui_zoom_shortcut boxrig_ui_zoom_shortcut_match(
    const boxrig_key_event *event);

/**
 * Resolves a portable logical key event to a background-opacity command.
 *
 * @param event Logical key identity and modifier state to inspect.
 * @return The matching command, or
 * BOXRIG_UI_BACKGROUND_OPACITY_SHORTCUT_NONE.
 *
 * @remarks Control plus the logical `<` and `>` symbols select decrease and
 * increase. Control+Shift+O selects toggle. Only the initial press is matched;
 * repeat, release, input-method text, and chords containing Alt, Super, Hyper,
 * or Meta are ignored.
 */
boxrig_ui_background_opacity_shortcut
boxrig_ui_background_opacity_shortcut_match(
    const boxrig_key_event *event);

/**
 * Resolves a portable logical key event to a clipboard command.
 *
 * @param event Logical key identity and modifier state to inspect.
 * @return The matching command, or BOXRIG_UI_CLIPBOARD_SHORTCUT_NONE.
 *
 * @remarks Control+Shift+C and Control+Shift+V select copy and paste.
 * Shift+Insert also selects paste. Only the initial press is matched; lock
 * modifiers do not affect matching, and chords containing Alt, Super, Hyper,
 * or Meta are ignored.
 */
boxrig_ui_clipboard_shortcut boxrig_ui_clipboard_shortcut_match(
    const boxrig_key_event *event);

/**
 * Applies one portable command to requested background opacity.
 *
 * @param shortcut Command to apply.
 * @param current_opacity Current requested eight-bit background opacity.
 * @param remembered_opacity Last requested translucent opacity, or 255 before
 * a translucent value has been selected.
 * @param next_opacity_out Receives the next requested eight-bit opacity.
 * @param next_remembered_opacity_out Receives the next remembered value.
 * @return True when the command changes opacity and both outputs are written;
 * otherwise false without writing either output.
 *
 * @remarks Opacity is converted to the nearest inclusive percentage before a
 * ten-percentage-point step and converted back with
 * `(percent * 255 + 50) / 100`. Steps clamp at zero and 100 rather than
 * wrapping. The first toggle from 100 percent selects 80 percent; later
 * toggles restore the most recent translucent value.
 */
bool boxrig_ui_background_opacity_shortcut_next(
    boxrig_ui_background_opacity_shortcut shortcut,
    uint8_t current_opacity,
    uint8_t remembered_opacity,
    uint8_t *next_opacity_out,
    uint8_t *next_remembered_opacity_out);

#endif
