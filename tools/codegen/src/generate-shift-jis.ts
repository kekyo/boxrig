import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { renderCodeTemplate } from './funcity-template.js';

// Keep the upstream index intact. The generated tables are boxrig-owned
// derivatives, with attribution carried into source and binary distributions.
const root = resolve(process.argv[2] ?? '.');
const bytes = await readFile(
  resolve(root, 'data/encoding/whatwg/index-jis0208.txt')
);
const metadata = JSON.parse(
  await readFile(resolve(root, 'data/encoding/whatwg/source.json'), 'utf8')
) as { files: { file: string; sha256: string }[] };
const hash = createHash('sha256').update(bytes).digest('hex');
if (
  metadata.files.find((entry) => entry.file === 'index-jis0208.txt')?.sha256 !==
  hash
)
  throw new Error(
    'The Shift_JIS source index does not match its recorded hash'
  );

const decode = new Array<number>(11280).fill(0);
const encode = new Map<number, number>();
for (const line of bytes.toString('utf8').split('\n')) {
  if (line.trim() === '' || line.startsWith('#')) continue;
  const match = /^\s*(\d+)\s+0x([0-9A-Fa-f]+)\s/.exec(line);
  if (match === null) throw new Error('Unexpected upstream index row');
  const pointer = Number(match[1]);
  const codepoint = Number.parseInt(match[2], 16);
  if (
    pointer >= decode.length ||
    codepoint <= 0 ||
    codepoint > 0xffff ||
    decode[pointer] !== 0
  )
    throw new Error('Unsupported upstream index value');
  decode[pointer] = codepoint;
  // WHATWG index Shift_JIS pointer excludes this duplicate range before
  // selecting the first pointer for a Unicode scalar.
  if ((pointer < 8272 || pointer > 8835) && !encode.has(codepoint))
    encode.set(codepoint, pointer);
}

const rows = Array.from({ length: decode.length / 8 }, (_, index) =>
  decode.slice(index * 8, index * 8 + 8)
);
const entries = [...encode].sort(([left], [right]) => left - right);
const generated = await renderCodeTemplate(
  `/* Generated by make generate-shift-jis; do not edit.
 * Source: https://encoding.spec.whatwg.org/index-jis0208.txt
 * SHA-256: {{hash}}
 * Copyright WHATWG (Apple, Google, Mozilla, Microsoft).
 * BSD-3-Clause for source code; see data/encoding/whatwg/LICENSE.
 */
#ifndef BOXRIG_SHIFT_JIS_TABLE_H
#define BOXRIG_SHIFT_JIS_TABLE_H

static const uint16_t shift_jis_decode[] = {
{{for row rows}}   {{for value row}} {{hex value}},{{end}}
{{end}}};

static const uint32_t shift_jis_encode[] = {
{{for entry entries}}    {{packed entry}},
{{end}}};

#endif
`,
  {
    hash,
    rows,
    entries,
    hex: (value: number) => `0x${value.toString(16).padStart(4, '0')}`,
    packed: ([codepoint, pointer]: [number, number]) =>
      `UINT32_C(0x${codepoint.toString(16).padStart(4, '0')}${pointer.toString(16).padStart(4, '0')})`,
  },
  'shift-jis-table.h.fc'
);
await writeFile(resolve(root, 'src/core/shift_jis_table.h'), generated);
console.log(
  `Generated ${decode.length} decode slots and ${entries.length} encode entries`
);
